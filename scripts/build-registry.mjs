// Builds registry.json (read by `shadcn build`), the example index used by the docs,
// and the combined component metadata, from registry/meta/*.json and registry/theme.json.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const site = JSON.parse(fs.readFileSync(path.join(root, "lib/site.json"), "utf8"));
const theme = JSON.parse(fs.readFileSync(path.join(root, "registry/theme.json"), "utf8"));
const metaDir = path.join(root, "registry/meta");
const itemUrl = (name) => `${site.url}/r/${name}.json`;

const metas = fs
  .readdirSync(metaDir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => JSON.parse(fs.readFileSync(path.join(metaDir, f), "utf8")));

const names = new Set(metas.map((m) => m.name));
const errors = [];

for (const m of metas) {
  for (const file of m.files ?? [`ui/${m.name}.tsx`]) {
    if (!fs.existsSync(path.join(root, "registry/lantern", file))) errors.push(`${m.name}: missing ${file}`);
  }
  for (const dep of m.registryDependencies ?? []) {
    if (!names.has(dep) && dep !== "utils") errors.push(`${m.name}: unknown registry dependency ${dep}`);
  }
  for (const ex of m.examples ?? []) {
    if (!fs.existsSync(path.join(root, "registry/lantern/examples", `${ex.name}.tsx`)))
      errors.push(`${m.name}: missing example ${ex.name}`);
  }
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const { radius, ...colors } = theme;
const themeItem = {
  name: "lantern-theme",
  type: "registry:theme",
  title: "Lantern theme",
  description: "Lantern colors, fonts, block shadows, the grid pattern and the pulse and blink animations.",
  cssVars: {
    theme: {
      "font-sans": 'var(--font-dm-sans), "DM Sans", ui-sans-serif, system-ui, sans-serif',
      "font-display": 'var(--font-space-grotesk), "Space Grotesk", ui-sans-serif, sans-serif',
      "shadow-block": "12px 14px 0 var(--shadow-block)",
      "shadow-block-sm": "6px 7px 0 var(--shadow-block)",
    },
    light: { ...colors, radius },
    dark: { ...colors, radius },
  },
  css: {
    "@utility bg-grid": {
      "background-image":
        "linear-gradient(var(--grid-line) 1px, transparent 1px), linear-gradient(90deg, var(--grid-line) 1px, transparent 1px)",
      "background-size": "20px 20px",
    },
    "@keyframes lantern-pulse": { "50%": { opacity: "0.35" } },
    "@keyframes lantern-blink": { "50%": { opacity: "0" } },
    "@utility animate-lantern-pulse": { animation: "lantern-pulse 2.4s ease-in-out infinite" },
    "@utility animate-lantern-blink": { animation: "lantern-blink 1.1s steps(1) infinite" },
  },
};

const order = ["Lantern", "Forms", "Display", "Overlays", "Navigation", "Feedback"];
metas.sort((a, b) => order.indexOf(a.category) - order.indexOf(b.category) || a.title.localeCompare(b.title));

const registry = {
  $schema: "https://ui.shadcn.com/schema/registry.json",
  name: "lantern",
  homepage: site.url,
  items: [
    themeItem,
    ...metas.map((m) => ({
      name: m.name,
      type: "registry:ui",
      title: m.title,
      description: m.description,
      dependencies: m.dependencies ?? [],
      registryDependencies: [
        "utils",
        itemUrl("lantern-theme"),
        ...(m.registryDependencies ?? []).filter((d) => d !== "utils").map(itemUrl),
      ],
      files: (m.files ?? [`ui/${m.name}.tsx`]).map((f) => ({ path: `registry/lantern/${f}`, type: "registry:ui" })),
    })),
  ],
};
fs.writeFileSync(path.join(root, "registry.json"), JSON.stringify(registry, null, 2) + "\n");

const examples = metas.flatMap((m) => (m.examples ?? []).map((e) => e.name));
const index =
  `// Generated by scripts/build-registry.mjs. Do not edit.\n` +
  `import type { ComponentType } from "react";\n` +
  examples.map((e, i) => `import E${i} from "@/registry/lantern/examples/${e}";`).join("\n") +
  `\n\nexport const examples: Record<string, ComponentType> = {\n` +
  examples.map((e, i) => `  ${JSON.stringify(e)}: E${i},`).join("\n") +
  `\n};\n`;
fs.writeFileSync(path.join(root, "registry/__index__.tsx"), index);
fs.writeFileSync(path.join(root, "registry/__meta__.json"), JSON.stringify(metas, null, 2) + "\n");

console.log(`registry: ${metas.length} components, ${examples.length} examples`);
